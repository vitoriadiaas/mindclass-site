-- MindClass — esquema para Supabase (PostgreSQL)
-- Como usar: painel do Supabase > SQL Editor > cole este arquivo inteiro > Run.
-- Pode ser executado mais de uma vez: não apaga nem sobrescreve dados.
--
-- Segurança: o acesso é feito SOMENTE pelo servidor do MindClass (conexão PostgreSQL direta).
-- Todas as tabelas ficam com RLS ligado e sem políticas, e os papéis anon/authenticated não têm
-- permissão. Assim, a chave publicável (sb_publishable_...) não lê nem grava nada.

begin;

create extension if not exists citext with schema extensions;

-- ============================ USUÁRIOS E PERFIS ============================
create table if not exists public.usuarios (
  id               bigint generated by default as identity primary key,
  nome             text not null check (char_length(nome) between 1 and 100),
  email            extensions.citext not null unique check (char_length(email::text) <= 120),
  senha_hash       text not null,                       -- scrypt (nunca a senha em texto puro)
  salt             text not null,
  perfil           text not null check (perfil in ('professor','aluno','administrador')),
  foto             text check (foto is null or char_length(foto) <= 400000),
  ativo            smallint not null default 1 check (ativo in (0,1)),
  ultimo_login     timestamptz,
  senha_alterada_em timestamptz,
  criado_em        timestamptz not null default now()
);

create table if not exists public.professores (
  usuario_id bigint primary key references public.usuarios(id) on delete cascade,
  turno      text not null check (turno in ('manhã','tarde','noite','integral'))
);

create table if not exists public.alunos (
  usuario_id bigint primary key references public.usuarios(id) on delete cascade,
  matricula  text check (char_length(matricula) <= 30)
);

-- ============================ MATÉRIAS, TURMAS E VÍNCULOS ============================
create table if not exists public.materias (
  id   bigint generated by default as identity primary key,
  nome extensions.citext not null unique
);

create table if not exists public.turmas (
  id           bigint generated by default as identity primary key,
  nome         extensions.citext not null unique,
  etapa        text not null default 'outra' check (etapa in ('fundamental','medio','outra')),
  num_horarios smallint not null default 9 check (num_horarios between 1 and 9)
);

create table if not exists public.professor_materias (
  professor_id bigint not null references public.professores(usuario_id) on delete cascade,
  materia_id   bigint not null references public.materias(id) on delete cascade,
  aprovado     smallint not null default 1 check (aprovado in (0,1)),  -- 0 = aguardando administração
  primary key (professor_id, materia_id)
);

create table if not exists public.professor_turmas (
  professor_id bigint not null references public.professores(usuario_id) on delete cascade,
  turma_id     bigint not null references public.turmas(id) on delete cascade,
  aprovado     smallint not null default 1 check (aprovado in (0,1)),
  primary key (professor_id, turma_id)
);

create table if not exists public.aluno_turmas (
  aluno_id bigint not null references public.alunos(usuario_id) on delete cascade,
  turma_id bigint not null references public.turmas(id) on delete cascade,
  primary key (aluno_id, turma_id)
);

-- ============================ HORÁRIOS E CALENDÁRIO ============================
create table if not exists public.horarios (
  id           bigint generated by default as identity primary key,
  turma_id     bigint not null references public.turmas(id) on delete cascade,
  materia_id   bigint not null references public.materias(id) on delete cascade,
  professor_id bigint not null references public.professores(usuario_id) on delete cascade,
  dia          smallint not null check (dia between 1 and 5),       -- 1 = segunda … 5 = sexta
  slot         smallint check (slot between 1 and 9),               -- 1ª aula, 2ª aula…
  inicio       time not null,
  fim          time not null,
  check (inicio < fim)
);

create table if not exists public.calendario (
  id         bigint generated by default as identity primary key,
  usuario_id bigint not null references public.usuarios(id) on delete cascade,
  turma_id   bigint references public.turmas(id) on delete cascade, -- nulo = evento pessoal
  materia_id bigint references public.materias(id) on delete set null,
  titulo     text not null check (char_length(titulo) between 1 and 80),
  descricao  text check (char_length(descricao) <= 300),
  categoria  text not null default 'evento' check (categoria in ('prova','trabalho','atividade','evento','reuniao','outro')),
  data       date not null,
  inicio     time,
  fim        time,
  check (inicio is null or fim is null or inicio < fim)
);

-- ============================ NOTAS (por trimestre) E ATIVIDADES ============================
create table if not exists public.notas (
  id            bigint generated by default as identity primary key,
  aluno_id      bigint not null references public.alunos(usuario_id) on delete cascade,
  materia_id    bigint not null references public.materias(id) on delete cascade,
  professor_id  bigint not null references public.professores(usuario_id),
  trimestre     smallint not null check (trimestre between 1 and 3),
  valor         numeric(3,1) not null check (valor between 0 and 10),
  descricao     text check (char_length(descricao) <= 200),
  atualizado_em timestamptz not null default now(),
  unique (aluno_id, materia_id, trimestre)
);

create table if not exists public.atividades (
  id           bigint generated by default as identity primary key,
  turma_id     bigint not null references public.turmas(id) on delete cascade,
  materia_id   bigint not null references public.materias(id) on delete cascade,
  professor_id bigint not null references public.professores(usuario_id) on delete cascade,
  titulo       text not null check (char_length(titulo) between 1 and 120),
  descricao    text check (char_length(descricao) <= 1000),
  prazo        timestamp not null,                    -- horário local da escola
  criado_em    timestamptz not null default now()
);

create table if not exists public.atividades_concluidas (
  aluno_id     bigint not null references public.alunos(usuario_id) on delete cascade,
  atividade_id bigint not null references public.atividades(id) on delete cascade,
  primary key (aluno_id, atividade_id)
);

-- ============================ NOTIFICAÇÕES E SESSÕES ============================
create table if not exists public.notificacoes (
  id         bigint generated by default as identity primary key,
  usuario_id bigint not null references public.usuarios(id) on delete cascade,
  tipo       text not null,
  titulo     text not null,
  mensagem   text,
  chave      text,                                    -- evita lembretes repetidos
  lida       smallint not null default 0 check (lida in (0,1)),
  criado_em  timestamptz not null default now()
);

create table if not exists public.sessoes (
  token_hash text primary key,                        -- SHA-256 do token do cookie
  usuario_id bigint not null references public.usuarios(id) on delete cascade,
  expira_em  timestamptz not null,
  ultimo_uso timestamptz not null default now()
);

-- ============================ HISTÓRICO DE NOTAS E AUDITORIA (imutáveis) ============================
create table if not exists public.notas_historico (
  id             bigint generated by default as identity primary key,
  aluno_id       bigint not null references public.alunos(usuario_id),
  materia_id     bigint not null references public.materias(id),
  turma_id       bigint references public.turmas(id),
  trimestre      smallint not null check (trimestre between 1 and 3),
  ano_letivo     smallint not null,
  acao           text not null check (acao in ('criada','alterada','excluida')),
  valor_anterior numeric(3,1),
  valor_novo     numeric(3,1),
  professor_id   bigint references public.usuarios(id),
  alterado_por   bigint not null references public.usuarios(id),
  alterado_em    timestamptz not null default now(),
  origem         text not null default 'sistema'
);

create table if not exists public.auditoria (
  id         bigint generated by default as identity primary key,
  usuario_id bigint references public.usuarios(id),
  acao       text not null,
  alvo       text,
  detalhe    text,
  ip         text,
  em         timestamptz not null default now()
);

create or replace function public.impedir_alteracao() returns trigger
language plpgsql set search_path = '' as $$
begin
  raise exception 'Os registros de % são imutáveis.', tg_table_name;
end $$;

drop trigger if exists notas_historico_imutavel on public.notas_historico;
create trigger notas_historico_imutavel before update or delete on public.notas_historico
  for each row execute function public.impedir_alteracao();

drop trigger if exists auditoria_imutavel on public.auditoria;
create trigger auditoria_imutavel before update or delete on public.auditoria
  for each row execute function public.impedir_alteracao();

-- ============================ ÍNDICES ============================
create unique index if not exists ux_notif_chave   on public.notificacoes (usuario_id, chave) where chave is not null;
create index if not exists ix_notif_user           on public.notificacoes (usuario_id, criado_em desc);
create index if not exists ix_usuarios_perfil      on public.usuarios (perfil, ativo);
create index if not exists ix_sess_usuario         on public.sessoes (usuario_id);
create index if not exists ix_prof_mat_materia     on public.professor_materias (materia_id);
create index if not exists ix_prof_turmas_turma    on public.professor_turmas (turma_id);
create index if not exists ix_aluno_turmas_turma   on public.aluno_turmas (turma_id);
create index if not exists ix_hor_turma            on public.horarios (turma_id, dia, slot);
create index if not exists ix_hor_prof             on public.horarios (professor_id, dia, slot);
create index if not exists ix_hor_materia          on public.horarios (materia_id);
create index if not exists ix_cal_turma            on public.calendario (turma_id, data);
create index if not exists ix_cal_usuario          on public.calendario (usuario_id, data);
create index if not exists ix_cal_materia          on public.calendario (materia_id);
create index if not exists ix_cal_data             on public.calendario (data);
create index if not exists ix_notas_materia        on public.notas (materia_id);
create index if not exists ix_notas_prof           on public.notas (professor_id);
create index if not exists ix_atv_turma            on public.atividades (turma_id, prazo);
create index if not exists ix_atv_prof             on public.atividades (professor_id, prazo);
create index if not exists ix_atv_materia          on public.atividades (materia_id);
create index if not exists ix_conc_atv             on public.atividades_concluidas (atividade_id);
create index if not exists ix_hist_aluno           on public.notas_historico (aluno_id, alterado_em desc);
create index if not exists ix_hist_materia         on public.notas_historico (materia_id, trimestre);
create index if not exists ix_hist_turma           on public.notas_historico (turma_id, alterado_em desc);
create index if not exists ix_hist_data            on public.notas_historico (alterado_em desc);
create index if not exists ix_hist_prof            on public.notas_historico (professor_id);
create index if not exists ix_hist_autor           on public.notas_historico (alterado_por);
create index if not exists ix_aud_data             on public.auditoria (em desc);
create index if not exists ix_aud_usuario          on public.auditoria (usuario_id);

-- ============================ BLOQUEIO DA API PÚBLICA ============================
do $$
declare t text;
begin
  foreach t in array array['usuarios','professores','alunos','materias','turmas','professor_materias','professor_turmas',
    'aluno_turmas','horarios','calendario','notas','atividades','atividades_concluidas','notificacoes','sessoes',
    'notas_historico','auditoria']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on table public.%I from anon, authenticated', t);
  end loop;
end $$;
revoke execute on function public.impedir_alteracao() from public, anon, authenticated;

